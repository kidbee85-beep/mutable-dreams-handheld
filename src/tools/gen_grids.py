"""Mutable Dreams for Trimui Brick, by Kid Bunka: Grids' drum map as a C table.

Reads the 25 nodes (node_0 .. node_24: 3 instruments x 32 steps each) from Mutable Instruments' Grids
(third_party/mi/grids/resources.cc, Emilie Gillet, GPL-3.0-or-later) and writes them, unchanged, with the
arrangement of grids/pattern_generator.cc's drum_map[5][5], as build/gen/grids_map.h.
usage: gen_grids.py RESOURCES.cc OUT.h"""
import re
import sys

src = open(sys.argv[1]).read()
nodes = {}
for m in re.finditer(r"const prog_uint8_t node_(\d+)\[\] PROGMEM = \{(.*?)\};", src, re.S):
    vals = [int(v.strip(), 0) for v in m.group(2).replace("\n", " ").split(",") if v.strip()]
    assert len(vals) == 96, (m.group(1), len(vals))
    nodes[int(m.group(1))] = vals
assert len(nodes) == 25, len(nodes)
grid = [[10, 8, 0, 9, 11], [15, 7, 13, 12, 6], [18, 14, 4, 5, 3], [23, 16, 21, 1, 2], [24, 19, 17, 20, 22]]
out = ["/* generated by tools/gen_grids.py from Mutable Instruments' Grids (Emilie Gillet, GPL-3.0-or-later):",
       " * the topographic drum map, 25 nodes of 3 instruments x 32 steps, as drum_map[5][5] arranges them */",
       "#pragma once", "#include <stdint.h>", "static const uint8_t GRIDS_NODES[25][96] = {"]
for i in range(25):
    out.append("    {" + ", ".join(str(v) for v in nodes[i]) + "},")
out.append("};")
out.append("static const uint8_t GRIDS_MAP[5][5] = {" + ", ".join("{" + ", ".join(map(str, r)) + "}" for r in grid) + "};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("grids: 25 nodes")
