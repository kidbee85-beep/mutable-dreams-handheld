#!/usr/bin/env python3
"""The Itinera journeys for the DREAM MAP, read from the unchanged 2.1 sources (app/dsp/itinera.inc and
app/itinera_view.c) into build/gen/itinera_map.h: each journey's 32 scene Biomes in the engine's own order (anchors
and extras interleaved, as ItineraPreset's constructor lays them out), the durations, the sections per duration and
pace, and the four chapter lines.   python3 tools/gen_itinera.py SOURCE_APP_DIR OUT_HEADER"""
import re, sys
app, out = sys.argv[1], sys.argv[2]
inc = open(f"{app}/dsp/itinera.inc").read()
view = open(f"{app}/itinera_view.c").read()
base = int(re.search(r"itinera_biome_base=(\d+)", inc)[1])
presets = re.findall(r'\{"([^"]+)",\s*\{([\d,\s]+)\},\s*\{([\d,\s]+)\},\s*(\d+),(\d+),(\d+)\}', inc)
assert len(presets) == 14, len(presets)
minutes = [int(x) for x in re.search(r"minutes\[4\]=\{([\d,]+)\}", inc)[1].split(",")]
sections = [[int(x) for x in g.split(",")] for g in re.findall(r"\{(\d+,\d+,\d+)\}", re.search(r"sections\[4\]\[3\]=\{(.+?)\};", inc)[1])]
story_block = re.search(r"story\[MD_ITINERA_PRESETS\]=\{(.+?)\};", view, re.S)[1]
stories = [s.split("\\0") for s in re.findall(r'"((?:[^"\\]|\\.)*)"', story_block)]
assert len(stories) == 14
lines = ["/* generated by tools/gen_itinera.py from the 2.1 sources: do not edit */",
         f"static const unsigned short ITIN_MINUTES[4] = {{{', '.join(map(str, minutes))}}};",
         "static const unsigned char ITIN_SECTIONS[4][3] = {" + ", ".join("{" + ", ".join(map(str, r)) + "}" for r in sections) + "};",
         "static const short ITIN_BIOMES[14][32] = {"]
for name, anchors, extras, *_ in presets:
    a = [int(x) for x in anchors.split(",")]; e = [int(x) for x in extras.split(",")]
    order = []
    for i in range(15):
        order += [a[i], e[i]]
    order += [e[15], a[15]]
    assert len(order) == 32 and all(x >= base for x in order)
    lines.append("    {" + ", ".join(map(str, order)) + "},   /* " + name + " */")
lines.append("};")
lines.append("static const char *const ITIN_STORY[14][4] = {")
for s in stories:
    s = (s + ["", "", "", ""])[:4]
    lines.append("    {" + ", ".join('"' + x.replace('"', '\\"') + '"' for x in s) + "},")
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
print(out)
